package blockchainer

/*
#include <stdlib.h>
#include "blockchainer_c.h"
*/
import "C"

import "unsafe"

// CredentialGate is anonymous membership admission (docs/design/CREDENTIAL_GATE.md,
// Option A). An issuer signs a member's attribute vector as a BBS credential; the
// member then admits itself to a role by proving in zero knowledge that it holds
// an issuer-signed credential whose tier clears the policy threshold and whose
// expiry has not passed — revealing nothing else.
//
// Option A is UNLINKABLE: two presentations of one credential cannot be
// correlated (strong privacy, weak Sybil resistance). Real per-epoch Sybil
// resistance is Option B, blocked on an upstream cryptolib BBS-pseudonym
// primitive.

// BBSKeypair is a credential issuer's BBS key (public 96 B, secret 32 B).
type BBSKeypair struct {
	Public []byte
	Secret []byte
}

// NewBBSIssuer derives an issuer keypair from >= 32 bytes of key material. The
// public key is the chain's issuer identity, committed via a CredentialPolicy.
func NewBBSIssuer(keyMaterial []byte) (*BBSKeypair, error) {
	ensure()
	a, err := unpackAccountBlob(takeBuf(C.blockchainer_bbs_keygen(bp(keyMaterial), C.size_t(len(keyMaterial)))))
	if err != nil {
		return nil, err
	}
	return &BBSKeypair{Public: a.Public, Secret: a.Secret}, nil
}

// CredentialPolicy is the membership rule a chain enforces. Its Encode/Hash are
// canonical, so the policy can be committed into the genesis hash (like an
// AssuranceProfile). AttributeCount must be 4 in this binding.
type CredentialPolicy struct {
	ChainID        uint64
	IssuerPublic   []byte // 96-byte BBS issuer public key
	Header         []byte // BBS issuance-domain string
	AttributeCount uint32
	MinTier        uint8

	encoded []byte // cached canonical encoding
}

// NewCredentialPolicy canonically encodes a policy (attributeCount must be 4).
func NewCredentialPolicy(chainID uint64, issuerPublic, header []byte, attributeCount uint32, minTier uint8) (*CredentialPolicy, error) {
	ensure()
	enc, err := takeBuf(C.blockchainer_credential_policy_encode(C.uint64_t(chainID),
		bp(issuerPublic), C.size_t(len(issuerPublic)), bp(header), C.size_t(len(header)),
		C.uint32_t(attributeCount), C.uint8_t(minTier)))
	if err != nil {
		return nil, err
	}
	return &CredentialPolicy{
		ChainID: chainID, IssuerPublic: issuerPublic, Header: header,
		AttributeCount: attributeCount, MinTier: minTier, encoded: enc,
	}, nil
}

// Encoded returns the policy's canonical bytes (the form the gate consumes).
func (p *CredentialPolicy) Encoded() []byte { return p.encoded }

// Hash is the 32-byte commitment to commit into genesis.
func (p *CredentialPolicy) Hash() ([]byte, error) {
	ensure()
	return takeBuf(C.blockchainer_credential_policy_hash(bp(p.encoded), C.size_t(len(p.encoded))))
}

// IssueCredential (issuer side, trusted-issuer model) assembles and BBS-signs a
// credential. memberSecret is 32 bytes generated by the member. The returned blob
// is HOLDER-SECRET (it carries memberSecret + hidden attributes) — store sealed.
func (p *CredentialPolicy) IssueCredential(issuerSecret, memberSecret []byte, tier uint8, notAfter uint64, issuerEpoch uint32) ([]byte, error) {
	ensure()
	return takeBuf(C.blockchainer_credential_issue(bp(p.encoded), C.size_t(len(p.encoded)),
		bp(issuerSecret), C.size_t(len(issuerSecret)), bp(memberSecret), C.size_t(len(memberSecret)),
		C.uint8_t(tier), C.uint64_t(notAfter), C.uint32_t(issuerEpoch)))
}

// Present (holder side) builds an unlinkable presentation for (epoch, scope,
// challenge). Discloses {tier, not_after, issuer_epoch}; proves the rest in ZK.
func (p *CredentialPolicy) Present(credential []byte, epoch uint32, scope string, challenge []byte) ([]byte, error) {
	ensure()
	cscope := C.CString(scope)
	defer C.free(unsafe.Pointer(cscope))
	return takeBuf(C.blockchainer_credential_present(bp(p.encoded), C.size_t(len(p.encoded)),
		bp(credential), C.size_t(len(credential)), C.uint32_t(epoch), cscope,
		bp(challenge), C.size_t(len(challenge))))
}

// CredentialGate is a verifier's admission gate (holds the issuer-epoch deny-list).
type CredentialGate struct{ h C.BlockchainerCredentialGate }

// NewCredentialGate opens a gate enforcing the policy.
func NewCredentialGate(p *CredentialPolicy) *CredentialGate {
	ensure()
	return &CredentialGate{C.blockchainer_credential_gate_new(bp(p.encoded), C.size_t(len(p.encoded)))}
}

func (g *CredentialGate) Free() { C.blockchainer_credential_gate_free(g.h) }

// RevokeIssuerEpoch bulk-revokes every credential issued in the given epoch.
func (g *CredentialGate) RevokeIssuerEpoch(epoch uint32) {
	C.blockchainer_credential_gate_revoke_epoch(g.h, C.uint32_t(epoch))
}

// Admit runs the full checklist (proof + expiry + revocation + tier), binding
// (epoch, scope, challenge, now). A malformed presentation is a quiet false.
func (g *CredentialGate) Admit(epoch uint32, scope string, challenge, presentation []byte, now uint64) bool {
	cscope := C.CString(scope)
	defer C.free(unsafe.Pointer(cscope))
	return C.blockchainer_credential_gate_admit(g.h, C.uint32_t(epoch), cscope,
		bp(challenge), C.size_t(len(challenge)), bp(presentation), C.size_t(len(presentation)),
		C.uint64_t(now)) == 1
}
